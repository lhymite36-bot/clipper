"""Copyright-safe music beds. Never downloads or rips audio from YouTube videos.

Sources, in order:
1. A user file passed with --music
2. The user's library folders (YouTube Audio Library drops, CC0/CC-BY files,
   and a 'my sounds' folder of audio they have the rights to)
3. Optional Pixabay Music (free key in .env) cached locally
4. A short original bed generated on the machine (no third-party audio)

Credits for anything used are returned so they can go in the YouTube description.
"""

from __future__ import annotations

import math
import wave
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from clipper.paths import default_music_dir, default_sounds_dir, user_data_dir

AUDIO_EXT = {".mp3", ".wav", ".m4a", ".aac", ".ogg", ".flac", ".opus"}

# Mood labels used to match a preset / energy level.
MOODS = {
    "story-skit": "warm",
    "cinematic-edit": "moody",
    "sports-montage": "energy",
    "auto": "warm",
}


@dataclass
class MusicPick:
    path: Path
    credit: str
    mood: str
    source: str  # library | generated | pixabay | user


def library_dirs(extra: list[Path | str] | None = None) -> list[Path]:
    dirs = [
        default_music_dir(),
        default_sounds_dir(),
        user_data_dir() / "my-sounds",
        Path.cwd() / "music",
        Path.cwd() / "sounds",
    ]
    for item in extra or []:
        if item:
            dirs.append(Path(item))
    # Unique, existing last — we still return not-yet-created defaults first
    # so callers can tell the user where to drop files.
    seen: set[Path] = set()
    out: list[Path] = []
    for d in dirs:
        d = d.expanduser()
        if d in seen:
            continue
        seen.add(d)
        out.append(d)
    return out


def list_tracks(extra: list[Path | str] | None = None) -> list[Path]:
    files: list[Path] = []
    for folder in library_dirs(extra):
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*")):
            if path.is_file() and path.suffix.lower() in AUDIO_EXT:
                files.append(path)
    return files


def _energy_score(path: Path, seconds: float = 8.0) -> float:
    """Rough loudness / brightness score in 0–1. 0.5 if we cannot read it."""
    try:
        from clipper.audio_peaks import load_mono_f32

        samples = load_mono_f32(path, rate=16000)
        if samples.size < 16:
            return 0.5
        n = min(samples.size, int(16000 * seconds))
        chunk = samples[:n]
        rms = float(np.sqrt(np.mean(np.square(chunk)) + 1e-9))
        # Zero-crossing rate as a cheap tempo/brightness hint.
        zc = float(np.mean(np.abs(np.diff(np.sign(chunk)))) / 2)
        return float(min(1.0, max(0.0, 0.65 * min(1.0, rms * 4) + 0.35 * min(1.0, zc * 8))))
    except Exception:
        return 0.5


def _wanted_energy(mood: str) -> float:
    return {"moody": 0.28, "warm": 0.45, "energy": 0.82, "hype": 0.9}.get(mood, 0.5)


def pick_music(
    preset: str = "auto",
    *,
    explicit: Path | str | None = None,
    extra_dirs: list[Path | str] | None = None,
    allow_generated: bool = True,
) -> MusicPick | None:
    if explicit:
        path = Path(explicit)
        if path.is_file():
            return MusicPick(path=path, credit="Music: supplied by the user.", mood=MOODS.get(preset, "warm"), source="user")
    mood = MOODS.get(preset, "warm")
    tracks = list_tracks(extra_dirs)
    if tracks:
        target = _wanted_energy(mood)
        ranked = sorted(tracks, key=lambda p: abs(_energy_score(p) - target))
        chosen = ranked[0]
        credit = f"Music: '{chosen.stem}' from the local Clipper library (use only tracks you have the rights to, e.g. YouTube Audio Library, CC0, or CC BY with credit)."
        return MusicPick(path=chosen, credit=credit, mood=mood, source="library")
    if allow_generated:
        path = _ensure_generated_bed(mood)
        return MusicPick(
            path=path,
            credit="Music: original bed generated by Clipper (no third-party recording).",
            mood=mood,
            source="generated",
        )
    return None


def _ensure_generated_bed(mood: str) -> Path:
    dest_dir = default_music_dir() / "generated"
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / f"clipper-{mood}-bed.wav"
    if dest.is_file() and dest.stat().st_size > 1000:
        return dest
    _write_generated_bed(dest, mood)
    return dest


def _write_generated_bed(dest: Path, mood: str, seconds: float = 32.0, rate: int = 44100) -> None:
    """A simple original loop: no samples from anyone else's catalogue."""
    n = int(seconds * rate)
    t = np.arange(n, dtype=np.float64) / rate
    if mood == "energy":
        # Punchy fifths + a light noise hat on eighths.
        root, fifth = 110.0, 165.0
        tone = 0.18 * np.sin(2 * math.pi * root * t) + 0.12 * np.sin(2 * math.pi * fifth * t)
        beat = ((t * 2) % 1.0) < 0.08
        hat = beat * (np.random.default_rng(3).uniform(-0.08, 0.08, n))
        wave_data = tone + hat
    elif mood == "moody":
        wave_data = (
            0.16 * np.sin(2 * math.pi * 98.0 * t)
            + 0.10 * np.sin(2 * math.pi * 146.8 * t + 0.3)
            + 0.06 * np.sin(2 * math.pi * 196.0 * t + 0.7)
        )
    else:
        # Warm: soft major triad, slow pulse.
        wave_data = (
            0.14 * np.sin(2 * math.pi * 130.81 * t)
            + 0.10 * np.sin(2 * math.pi * 164.81 * t)
            + 0.08 * np.sin(2 * math.pi * 196.00 * t)
        )
        pulse = 0.65 + 0.35 * np.sin(2 * math.pi * 0.5 * t)
        wave_data *= pulse
    # Fade ends so a loop is less clicky.
    fade = int(0.04 * rate)
    env = np.ones(n, dtype=np.float64)
    env[:fade] = np.linspace(0, 1, fade)
    env[-fade:] = np.linspace(1, 0, fade)
    samples = np.clip(wave_data * env * 0.55, -0.89, 0.89)
    pcm = (samples * 32767.0).astype(np.int16)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(dest), "w") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(rate)
        wf.writeframes(pcm.tobytes())


def duck_filter(speech: str = "src", bed: str = "bed", out: str = "aout", bed_volume: float = 0.16) -> str:
    """Duck the bed under speech with a side-chain compressor."""
    vol = max(0.04, min(0.5, float(bed_volume)))
    return (
        f"[{speech}]aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=stereo[voice];"
        f"[{bed}]volume={vol:.3f},aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=stereo[bg];"
        f"[bg][voice]sidechaincompress=threshold=0.05:ratio=6:attack=40:release=280:level_sc=1[ducked];"
        f"[voice][ducked]amix=inputs=2:duration=first:dropout_transition=0:normalize=0[{out}]"
    )
